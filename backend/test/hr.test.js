test('HR API: authentication, role boundaries, validation and persistence', async t => {
  const key = 'local-hr-test-key';
  const previousSecret = process.env.JWT_SECRET;
  process.env.JWT_SECRET = key;
  const actorId = '000000000000000000000001';
  const targetId = '000000000000000000000002';
  let actor = { _id: actorId, role: 'HR_ADMIN', status: 'ACTIVE' };
  let target = { _id: targetId, role: 'EMPLOYEE', name: 'Test', email: 'test@example.com', department: 'Engineering', status: 'ACTIVE' };
  let subordinate = null;
  let pending = null;
  let persisted;
  let audit = 0;
  const originals = { findById: User.findById, find: User.find, create: User.create, update: User.findOneAndUpdate, exists: User.exists, requestExists: Request.exists, requestFind: Request.findOne, audit: AuditLog.create };
  const doc = value => ({ ...value, toObject() { return { ...value }; } });
  User.findById = id => {
    const value = String(id) === actorId ? actor : target;
    const promise = Promise.resolve(value && doc(value));
    promise.select = async () => value && doc(value);
    return promise;
  };
  User.find = () => ({ select: () => ({ sort: async () => [doc(target)] }) });
  User.exists = async () => subordinate;
  Request.exists = async () => pending;
  User.create = async values => { persisted = values; return doc({ _id: targetId, ...values }); };
  User.findOneAndUpdate = (_filter, update) => ({ select: async () => { persisted = update.$set; return doc({ ...target, ...update.$set }); } });
  AuditLog.create = async () => { audit++; };
  const app = express(); app.use(express.json()); app.use('/api/hr', hrRouter);
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => {
    await new Promise(resolve => server.close(resolve));
    User.findById = originals.findById; User.find = originals.find; User.create = originals.create;
    User.findOneAndUpdate = originals.update; User.exists = originals.exists;
    Request.exists = originals.requestExists; Request.findOne = originals.requestFind; AuditLog.create = originals.audit;
    if (previousSecret === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = previousSecret;
  });
  const base = `http://127.0.0.1:${server.address().port}/api/hr/users`;
  const headers = { 'Content-Type': 'application/json', Authorization: `Bearer ${jwt.sign({ id: actorId }, key)}` };
  const call = (method, body, id = '') => fetch(base + id, { method, headers, ...(body && { body: JSON.stringify(body) }) });
  assert.equal((await fetch(base)).status, 401);
  actor.role = 'EMPLOYEE'; assert.equal((await call('GET')).status, 403);
  actor.role = 'HR_ADMIN'; actor.status = 'INACTIVE'; assert.equal((await call('GET')).status, 401);
  actor.status = 'ACTIVE'; assert.equal((await call('GET')).status, 200);
  let attachmentScope;
  Request.findOne = async query => { attachmentScope = query; return { attachment: '/uploads/../../.env' }; };
  const attachment = await fetch(base.replace('/users', `/requests/${targetId}/attachment`), { headers });
  assert.equal(attachment.status, 404);
  assert.equal(attachmentScope.status.$ne, 'DRAFT');
  assert.ok(!attachmentScope.type.$in.includes('PURCHASE'));
  const body = { name: 'New Person', email: 'NEW@example.com', role: 'EMPLOYEE', department: 'Engineering', password: 'Password123' };
  assert.equal((await call('POST', { ...body, role: 'SYSTEM_ADMIN' })).status, 400);
  assert.equal((await call('POST', { ...body, name: {} })).status, 400);
  const created = await call('POST', body);
  assert.equal(created.status, 201);
  assert.equal(persisted.email, 'new@example.com');
  assert.notEqual(persisted.password, body.password);
  assert.equal((await created.json()).data.password, undefined);
  target.role = 'DIRECTOR'; assert.equal((await call('PATCH', { status: 'INACTIVE' }, '/' + targetId)).status, 403);
  target.role = 'EMPLOYEE';
  assert.equal((await call('PATCH', { role: 'HR_ADMIN' }, '/' + targetId)).status, 400);
  subordinate = { _id: actorId };
  assert.equal((await call('PATCH', { status: 'INACTIVE' }, '/' + targetId)).status, 409);
  subordinate = null; pending = { _id: actorId };
  assert.equal((await call('PATCH', { status: 'INACTIVE' }, '/' + targetId)).status, 409);
  pending = null;
  assert.equal((await call('PATCH', { status: 'INACTIVE', password: 'ignored' }, '/' + targetId)).status, 200);
  assert.deepEqual(persisted, { status: 'INACTIVE' });
  assert.equal(audit, 2);
});

test('HR workflow preserves attendance and training routing', () => {
  const hr = WORKFLOW.PENDING_HRADMIN;
  assert.ok(hr.types.includes(REQUEST_TYPES.ATTENDANCE));
  assert.equal(hr.next({ type: REQUEST_TYPES.LEAVE }), 'APPROVED');
  assert.equal(hr.next({ type: REQUEST_TYPES.TRAINING, amount: 500 }), 'PENDING_ACCOUNTANT');
  assert.equal(hr.next({ type: REQUEST_TYPES.TRAINING, amount: 0 }), 'APPROVED');
  assert.ok(!hr.types.includes(REQUEST_TYPES.PURCHASE));
});

test('HR decisions reject wrong stage/type/self, persist history and detect stale updates', async t => {
  const original = { find: Request.findById, update: Request.findOneAndUpdate, session: mongoose.startSession, audit: AuditLog.create, fetch: globalThis.fetch };
  t.after(() => { Request.findById = original.find; Request.findOneAndUpdate = original.update; mongoose.startSession = original.session; AuditLog.create = original.audit; globalThis.fetch = original.fetch; });
  const actor = new mongoose.Types.ObjectId();
  const author = new mongoose.Types.ObjectId();
  const id = new mongoose.Types.ObjectId();
  let doc;
  let saved;
  let conflict = false;
  Request.findById = () => ({ populate: async () => doc });
  Request.findOneAndUpdate = async (_filter, update) => { saved = update; return conflict ? null : { ...doc, ...update.$set }; };
  mongoose.startSession = async () => ({ withTransaction: async fn => fn(), endSession: async () => {} });
  AuditLog.create = async () => {};
  globalThis.fetch = async () => new Response('{"id":"local-test-email"}', { status: 200, headers: { 'Content-Type': 'application/json' } });
  const decide = async (overrides = {}, body = {}) => {
    saved = null;
    doc = { _id: id, title: 'Test', type: 'LEAVE', status: 'PENDING_HRADMIN', amount: 0, author: { _id: author, name: 'Employee', email: 'test@example.invalid' }, ...overrides };
    const res = { statusCode: 200, status(code) { this.statusCode = code; return this; }, json(value) { this.body = value; return this; } };
    await updateRequestStatus({ params: { id: String(id) }, user: { _id: actor, role: 'HR_ADMIN', name: 'HR' }, body: { action: 'APPROVED', ...body }, headers: {} }, res);
    return res;
  };
  assert.equal((await decide({ status: 'PENDING_MANAGER' })).statusCode, 403);
  assert.equal((await decide({ type: 'PURCHASE' })).statusCode, 403);
  assert.equal((await decide({ author: { _id: actor } })).statusCode, 403);
  assert.equal((await decide({ status: 'APPROVED' })).statusCode, 400);
  assert.equal((await decide({}, { action: 'REJECTED', comment: 'short' })).statusCode, 400);
  assert.equal((await decide()).statusCode, 200);
  assert.equal(saved.$set.status, 'APPROVED');
  assert.equal(saved.$push.approvalHistory.role, 'HR_ADMIN');
  assert.equal((await decide({ type: 'TRAINING', amount: 100 })).statusCode, 200);
  assert.equal(saved.$set.status, 'PENDING_ACCOUNTANT');
  conflict = true;
  assert.equal((await decide()).statusCode, 409);
});
