import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import jwt from 'jsonwebtoken';
import bcrypt from 'bcryptjs';
import mongoose from 'mongoose';
import router from '../src/Router/admin.js';
import User from '../src/models/User.js';
import Department from '../src/models/Department.js';
import Request from '../src/models/Request.js';
import AuditLog from '../src/models/Auditlog.js';
import SystemSettings from '../src/models/SystemSettings.js';

test('System Admin API reads real-shaped data, enforces roles and protects account operations', async t => {
  const originals = [];
  const mock = (object, key, value) => { originals.push(() => { object[key] = value; }); object[key] = value; };
  mock(SystemSettings, 'findOne', () => ({ maxTimeMS() { return this; }, lean: async () => null }));
  const secret = process.env.JWT_SECRET;
  process.env.JWT_SECRET = 'local-admin-tests';
  const actorId = '000000000000000000000001', targetId = '000000000000000000000002', deptId = '000000000000000000000003';
  const actor = { _id: actorId, name: 'Admin', role: 'SYSTEM_ADMIN', status: 'ACTIVE', tokenVersion: 0 };
  const target = { _id: targetId, name: 'HR', email: 'hr@example.invalid', department: 'HR', role: 'HR_ADMIN', status: 'ACTIVE', password: 'hidden', createdAt: new Date() };
  const chain = data => ({ select() { return this; }, populate() { return this; }, sort() { return this; }, session() { return this; }, skip() { return this; }, limit() { return this; }, lean: async () => data, then(resolve, reject) { return Promise.resolve(data).then(resolve, reject); } });
  let update, accountQuery, logQuery, logWrites = [], adminCount = 2;
  mock(User, 'findById', () => chain(actor));
  mock(User, 'find', query => { accountQuery = query; return chain([actor, target]); });
  mock(User, 'distinct', async () => ['HR', 'Engineering']);
  mock(User, 'exists', () => chain(null));
  mock(User, 'findOne', () => chain(target));
  mock(User, 'countDocuments', () => chain(adminCount));
  mock(User, 'create', async values => { update = values; return { _id: targetId, ...values }; });
  mock(User, 'findOneAndUpdate', (filter, change) => { update = change; return chain(String(filter._id) === actorId ? actor : { ...target, ...change.$set }); });
  mock(Department, 'find', () => chain([{ _id: deptId, name: 'HR' }]));
  mock(Department, 'findById', () => chain({ _id: deptId, name: 'HR' }));
  mock(Request, 'exists', () => chain(null));
  mock(mongoose, 'startSession', async () => ({ withTransaction: async fn => fn(), endSession: async () => {} }));
  mock(AuditLog, 'create', async value => { logWrites.push(value); });
  mock(AuditLog, 'countDocuments', async query => { logQuery = query; return 1; });
  mock(AuditLog, 'find', () => chain([{ _id: targetId, actor, action: 'CREATE_USER', targetEntity: 'User', targetId, createdAt: new Date(), changes: { newValue: { name: 'HR', password: 'do-not-expose', nested: { token: 'do-not-expose', visible: true } } } }]));
  const app = express(); app.use(express.json()); app.use('/api/admin', router);
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); originals.reverse().forEach(restore => restore()); if (secret === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = secret; });
  const base = `http://127.0.0.1:${server.address().port}/api/admin`;
  const call = (path, method = 'GET', body, version = 0) => fetch(base + path, { method, headers: { Authorization: `Bearer ${jwt.sign({ id: actorId, version }, process.env.JWT_SECRET)}`, 'Content-Type': 'application/json' }, ...(body && { body: JSON.stringify(body) }) });
  actor.role = 'HR_ADMIN'; assert.equal((await call('/accounts')).status, 403);
  actor.role = 'SYSTEM_ADMIN';
  const accounts = await (await call('/accounts')).json();
  assert.equal(accounts.accounts.length, 2);
  assert.deepEqual(accountQuery.role.$in, ['DIRECTOR', 'HR_ADMIN', 'SYSTEM_ADMIN']);
  assert.equal(accounts.accounts[0].isCurrentUser, true);
  assert.equal(accounts.accounts[1].password, undefined);
  assert.ok(accounts.departments.some(d => d.name === 'Engineering'));
  assert.equal((await call('/accounts', 'POST', { name: 'No', email: 'no@example.invalid', role: 'EMPLOYEE', departmentId: deptId })).status, 400);
  const created = await call('/accounts', 'POST', { name: 'Director', email: 'DIRECTOR@example.invalid', role: 'DIRECTOR', departmentId: deptId });
  assert.equal(created.status, 201);
  const result = await created.json();
  assert.ok(await bcrypt.compare(result.temporaryPassword, update.password));
  assert.equal(update.email, 'director@example.invalid');
  assert.ok(!JSON.stringify(logWrites).includes(result.temporaryPassword));
  assert.equal((await call(`/accounts/${actorId}/status`, 'PATCH', { status: 'INACTIVE' })).status, 403);
  target.role = 'SYSTEM_ADMIN'; adminCount = 1;
  assert.equal((await call(`/accounts/${targetId}/status`, 'PATCH', { status: 'INACTIVE' })).status, 409);
  adminCount = 2; target.role = 'HR_ADMIN';
  assert.equal((await call(`/accounts/${targetId}/status`, 'PATCH', { status: 'INACTIVE' })).status, 200);
  assert.equal(update.$inc.tokenVersion, 1);
  const reset = await call(`/accounts/${targetId}/reset-password`, 'POST');
  assert.equal(reset.status, 200);
  assert.equal(update.$inc.tokenVersion, 1);
  const logs = await (await call('/logs?result=SUCCESS&from=2026-11-18&to=2026-11-18')).json();
  assert.equal(logs.total, 1);
  assert.equal(logs.items[0].actorName, 'Admin');
  assert.equal(logs.items[0].newValue.password, undefined);
  assert.deepEqual(logs.items[0].newValue.nested, { visible: true });
  assert.equal(logQuery.createdAt.$gte.toISOString(), '2026-11-17T17:00:00.000Z');
  assert.equal((await call('/logs?from=2026-02-30')).status, 400);
  assert.equal((await call('/logs?page=-1')).status, 400);
  actor.tokenVersion = 1;
  assert.equal((await call('/accounts')).status, 401);
});
