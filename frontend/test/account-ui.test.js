import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { MemoryRouter } from 'react-router-dom';

test('accountant pages use saved preferences, localize labels and retain real request text and links', async t => {
  const server = await createServer({ root: fileURLToPath(new URL('..', import.meta.url)), mode: 'demo', server: { middlewareMode: true, open: false, ws: false }, appType: 'custom' });
  const previous = globalThis.localStorage;
  t.after(async () => { await server.close(); if (previous === undefined) delete globalThis.localStorage; else globalThis.localStorage = previous; });
  const { AdminPreferencesProvider } = await server.ssrLoadModule('/src/views/AdminPreferences.jsx');
  const { default: Dashboard } = await server.ssrLoadModule('/src/views/Account_Manager/AccountDashboard.jsx');
  const { default: Overview } = await server.ssrLoadModule('/src/views/Account_Manager/components/AccountOverview.jsx');
  const { default: Approvals } = await server.ssrLoadModule('/src/views/Account_Manager/components/AccountApprovals.jsx');
  const { default: Payments } = await server.ssrLoadModule('/src/views/Account_Manager/components/AccoutnPayments.jsx');
  const { default: PaymentForm } = await server.ssrLoadModule('/src/views/Account_Manager/components/PaymentForm.jsx');
  const { default: BudgetForm } = await server.ssrLoadModule('/src/views/Account_Manager/components/BudgetForm.jsx');
  const { canDecide } = await server.ssrLoadModule('/src/views/Account_Manager/AccountData.jsx');
  const actor = { id: 'accountant', role: 'accountant', name: 'Nguyễn Kế Toán', email: 'accountant@example.test' };
  const row = { _id: 'purchase', title: 'Thiết bị cho Nguyễn Văn A', type: 'PURCHASE', category: 'EQUIPMENT', author: { _id: 'employee', name: 'Nguyễn Văn A' }, status: 'PENDING_ACCOUNTANT', amount: 1234567 };
  const self = { ...row, _id: 'own-purchase', author: { _id: actor.id, name: actor.name } };
  assert.equal(canDecide(row, actor), true);
  assert.equal(canDecide(self, actor), false);
  assert.equal(canDecide({ ...row, author: null }, actor), false);
  assert.equal(canDecide({ ...row, status: 'PENDING_MANAGER' }, actor), false);
  assert.equal(canDecide({ ...row, type: 'LEAVE' }, actor), false);
  assert.equal(canDecide(row, { ...actor, role: 'hr_admin' }), false);
  for (const lang of ['vi','en']) for (const theme of ['light','dark']) {
    globalThis.localStorage = { getItem: key => key === 'flowrequest_admin_preferences' ? JSON.stringify({ lang, theme }) : null, setItem: () => {} };
    const render = component => renderToStaticMarkup(React.createElement(MemoryRouter, { initialEntries: ['/account'] }, React.createElement(AdminPreferencesProvider, null, component)));
    const shell = renderToStaticMarkup(React.createElement(MemoryRouter, { initialEntries: ['/account'] }, React.createElement(Dashboard, { user: actor, token: 'test-token' })));
    assert.ok(shell.includes(`data-theme="${theme}"`));
    assert.ok(shell.includes(`lang="${lang}"`));
    assert.ok(shell.includes(actor.name));
    assert.ok(shell.includes('href="/account/approvals"'));
    assert.ok(shell.includes('href="/account/payments"'));
    assert.ok(shell.includes(lang === 'en' ? 'Financial overview' : 'Tổng quan tài chính'));
    assert.ok(shell.includes(lang === 'en' ? 'Switch to Vietnamese' : 'Chuyển sang tiếng Anh'));
    assert.ok(shell.includes(lang === 'en' ? (theme === 'dark' ? 'Switch to light mode' : 'Switch to dark mode') : (theme === 'dark' ? 'Chuyển sang giao diện sáng' : 'Chuyển sang giao diện tối')));
    const overview = render(React.createElement(Overview, { requests: [row], onView: () => {} }));
    assert.ok(overview.includes(row.title));
    assert.ok(overview.includes(lang === 'en' ? 'Approved value' : 'Giá trị đã duyệt'));
    const approvals = render(React.createElement(Approvals, { requests: [row, self], user: actor }));
    assert.ok(approvals.includes('Nguyễn Văn A'));
    assert.ok(approvals.includes(lang === 'en' ? 'Equipment' : 'Thiết bị'));
    assert.ok(approvals.includes(lang === 'en' ? 'Pending accountant' : 'Chờ Kế toán'));
    assert.equal((approvals.match(/class="acc-review-button"/g) || []).length, 1);
    const payments = render(React.createElement(Payments));
    assert.ok(payments.includes(lang === 'en' ? 'Payment history' : 'Lịch sử thanh toán'));
    assert.ok(payments.includes(lang === 'en' ? 'Approved requests and outstanding expenses' : 'Đơn đã duyệt và chi phí cần thanh toán'));
    assert.ok(payments.includes('href="/account/approvals"'));
    const paid = { id: 'approved-request', title: 'Approved fixture', type: 'PURCHASE', author: { id: 'employee', name: 'Requester' }, approvedAmount: 10000000, paidAmount: 4000000, remainingAmount: 6000000, approvedAt: '2026-01-01T00:00:00Z', paymentAllowed: true };
    const finance = { approvedAmount: 10000000, paidAmount: 4000000, outstandingAmount: 6000000, requests: [paid, { ...paid, id: 'blocked-request', paymentAllowed: false, needsPaymentReview: true }], budgets: [{ id: 'department', name: 'Actual Department', revision: 2, allocatedAmount: 50000000, committedAmount: 10000000, availableAmount: 40000000, paidAmount: 4000000 }], departmentOptions: ['Actual Department'] };
    const financialPage = render(React.createElement(Payments, { finance }));
    assert.equal((financialPage.match(/class="acc-review-button"/g) || []).length, 1);
    assert.ok(financialPage.includes('Actual Department'));
    assert.ok(financialPage.includes(lang === 'en' ? 'Recorded payments' : 'Thực trả đã ghi nhận'));
    assert.ok(financialPage.includes(lang === 'en' ? 'Payment figures require reconciliation.' : 'Số liệu thanh toán cần đối soát.'));
    const paymentForm = render(React.createElement(PaymentForm, { row: paid }));
    assert.ok(paymentForm.includes('max="6000000"'));
    assert.ok(paymentForm.includes('type="file" required=""'));
    const budgetForm = render(React.createElement(BudgetForm, { budget: finance.budgets[0], departmentOptions: [] }));
    assert.ok(budgetForm.includes('min="10000000"'));
    assert.equal(budgetForm.includes(lang === 'en' ? 'Opening committed amount' : 'Số đã cam kết ban đầu'), false);
  }
});
